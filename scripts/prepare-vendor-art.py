"""Build v0.15.2 sanctuary components and registered approach/grip atlases."""
from pathlib import Path
from PIL import Image,ImageDraw
from scipy import ndimage
import numpy as np
import json,hashlib

ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'assets/vendors/source/v0152'
OUT=ROOT/'assets/vendors/v0152';OUT.mkdir(exist_ok=True)

def components(name,count,rows):
    im=Image.open(SRC/name).convert('RGBA');a=np.array(im)
    labels,_=ndimage.label(a[:,:,3]>90);sizes=np.bincount(labels.ravel());sizes[0]=0
    items=[]
    for k in np.argsort(sizes)[-count:]:
        if sizes[k]<1000:raise ValueError((name,'Incomplete source silhouettes'))
        m=labels==k;y,x=np.where(m)
        box=(max(0,int(x.min())-3),max(0,int(y.min())-3),min(im.width,int(x.max())+4),min(im.height,int(y.max())+4))
        copy=a.copy();copy[:,:,3]=np.where(ndimage.binary_dilation(m,iterations=3),a[:,:,3],0)
        items.append((min(rows-1,int((y.min()+y.max())*.5/im.height*rows)),float(x.mean()),Image.fromarray(copy).crop(box)))
    return [v[2] for v in sorted(items,key=lambda v:(v[0],v[1]))]

for kind in ['angel','devil']:
    parts=components(kind+'-sanctuary.png',3,2)
    # The broad low component is the platform, regardless of label-size order.
    floor=max(parts,key=lambda im:im.width/im.height)
    props=[im for im in parts if im is not floor]
    atlas=Image.new('RGBA',(768,768))
    for i,im in enumerate(props):
        im.thumbnail((356,730),Image.Resampling.LANCZOS)
        atlas.alpha_composite(im,(i*384+(384-im.width)//2,740-im.height))
    atlas.save(OUT/(kind+'-architecture.png'),optimize=True)
    floor.thumbnail((768,120),Image.Resampling.LANCZOS)
    tile=Image.new('RGBA',(768,128));tile.alpha_composite(floor,((768-floor.width)//2,0))
    tile.save(OUT/(kind+'-floor.png'),optimize=True)

atlas=Image.new('RGBA',(2048,1536));registration=[]
for i,im in enumerate(components('reaper-approach.png',12,3)):
    a=np.array(im);solid=a[:,:,3]>180
    cyan=solid&(a[:,:,1]>115)&(a[:,:,2]>120)&(a[:,:,0]<a[:,:,1]*.75)
    y,x=np.where(cyan)
    if not len(x):raise ValueError(('Missing eye',i))
    eye=(float(np.median(x)),float(np.median(y)))
    foot=float(np.where(solid.any(axis=1))[0][-1]);factor=260/(foot-eye[1])
    pos=(300-eye[0]*factor,480-foot*factor)
    tile=Image.new('RGBA',(512,512))
    resized=im.resize((round(im.width*factor),round(im.height*factor)),Image.Resampling.LANCZOS)
    tile.alpha_composite(resized,(round(pos[0]),round(pos[1])))
    atlas.alpha_composite(tile,((i%4)*512,(i//4)*512))
    registration.append({'eye':[round(v,2) for v in eye],'factor':round(factor,5)})
atlas.save(OUT/'reaper-approach.png',optimize=True)

